def compile_blocks(block_type, layer):
    """
    Recursively grab any nn.Models out of a model in a
    depth first search
    """
    if isinstance(layer, block_type):
        yield layer
    else:
        for child in layer.children():
            for x in compile_blocks(block_type, child):
                yield x

def recursively_set_requires_grad(layer, value):
    """
    Recursively set required_grad on all nn.Modules
    """
    layer.requires_grad = value
    for child in  layer.children():
        recursively_set_requires_grad(child, value)

def build_required_grad_thunk(layer):
    """
    Build a thunk which will recursively set required_grad = True
    on all nn.Modules
    """
    def execute():
        recursively_set_requires_grad(layer, True)

    return execute

def evaluate_loss_values(loss_values, depth):
    pivot = len(loss_values) // 2
    first_half = sum(loss_values[0:pivot]) / pivot
    second_half = sum(loss_values[pivot:]) / (len(loss_values) - pivot)

    #todo document this + full class
    if first_half / second_half >= 1.005:
        return False

    if depth <= 1 or len(loss_values) < 10:
        return True

    return evaluate_loss_values(loss_values[pivot:], depth - 1)

class Scheduler():
    """
    A custom scheduler which incrementally unfreezes layers
    when the loss value is not improving
    """
    def __init__(self, model, optimizer, requires_grad_type, batch_average_count, n_epochs, steps_per_epoch):
        """
        model:
            the model to update
        requires_grad_type:
            A type which is a subclass of nn.Module
            The scheduler will work backwards through modules
            of this type setting requires_grad = True when the
            model is not learning
        batch_average_count:
            Number of batches to use when evaluating whether the
            model is learning or not
        """

        self.model = model
        self.loss_values = []
        self.requires_grad_layers = list(
            map(build_required_grad_thunk, compile_blocks(requires_grad_type, model))
        )
        self.unfreezable = len(self.requires_grad_layers)
        self.batch_average_count = batch_average_count

        self.lr_scheduler = OneCycleLR(
          optimizer,
          max_lr=0.01,
          steps_per_epoch=steps_per_epoch,
          epochs=n_epochs,
          anneal_strategy="linear",
          pct_start=0.4)

    def step(self, loss):
        """
        Execute scheduling
        loss:
            the latest loss value
        returns:
            True if the model was modified or a modification was
            not required
            False if a modification was required but all layers
            have already been updated
        """
        self.loss_values.append(loss)
        if len(self.loss_values) < self.batch_average_count:
            # print(len(self.loss_values) , self.batch_average_count)
            return True

        result = self.evaluate()
        # keep fixed size of loss values to evaluate
        if len(self.loss_values) > 0: self.loss_values.pop(0)
        return result

    def evaluate(self):
        pivot = len(self.loss_values) // 2
        first_half = sum(self.loss_values[0:pivot]) / pivot
        second_half = sum(self.loss_values[pivot:]) / (len(self.loss_values) - pivot)

        # print("f", first_half, "s", second_half, "t", first_half / second_half)

        #todo document this + full class
        if not evaluate_loss_values(self.loss_values, 2):
            return True

        result = self.set_next()

        # remove the first half of stats to give the
        # scheduler time to re-evaluate
        if result:
            self.loss_values = self.loss_values[pivot:]

        return result

    def set_next(self):
        if len(self.requires_grad_layers) == 0:
            return False

        print(f"Unfreezing layer {len(self.requires_grad_layers)} of {self.unfreezable}")
        set_requires_grad = self.requires_grad_layers.pop()
        set_requires_grad()
        return True

