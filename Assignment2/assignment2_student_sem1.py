def compile_stats(stats):
    """
    Build loss and accuracy stats from a list of batch results

    stats:
        [ (batch 1 size, batch 1 loss, batch 1 acc ratio),
          (batch 2 size, batch 2 loss, batch 2 acc ratio),
          ...
        ]
    """

    _, loss, results = zip(*stats)
    avg_loss = torch.as_tensor(loss).mean().item()
    avg_acc = torch.as_tensor(results).mean().item()

    return avg_loss, avg_acc

class Trainer():
    def __init__(self, model, data_train, data_val, device,
                 requires_grad_type,
                 batch_size=256,
                 lr=0.001,
                 weight_decay=0.0,
                 images_per_checkpoint=1_000,
                 n_epochs=20):
        """
        images_per_checkpoint:  the number of images to process before emitting
                                and event to the tensorboard writer
        """
        self.device = device
        self.model = model.to(device)
        self.images_per_checkpoint = images_per_checkpoint
        self.data_train = DataLoader(dataset=data_train, batch_size=batch_size, shuffle=True)
        self.data_val = DataLoader(dataset=data_val, batch_size=batch_size, shuffle=False)

        # def __init__(self, model, optimizer, requires_grad_type, batch_average_count, epochs, steps_per_epoch):
        self.optimizer = optim.Adam(self.model.parameters(), lr=lr, weight_decay=weight_decay)
        self.scheduler = Scheduler(self.model, self.optimizer, requires_grad_type,
                                   batch_average_count=10_000 // batch_size, n_epochs=n_epochs, steps_per_epoch=len(self.data_train))
        self.loss_fn = nn.CrossEntropyLoss()
        self.checkpoint = 0
        self.train_stats = []
        self.n_epochs = n_epochs

    def train(self):
        """
        Train the entire model
        """

        for e in range(1, self.n_epochs + 1):
            print(f"Starting epoch {e}")

            for batch_result in self.train_one_epoch():
                yield e, batch_result

    def train_one_epoch(self):
        """
        Train a single epoch
        """

        for data in self.data_train:
            batch_result = self.train_and_log_batch(data)
            if batch_result: yield batch_result

    def train_and_log_batch(self, batch):
        """
        Train a single batch and return a training set result
        if required (determined by images_per_checkpoint)
        """

        # odd case when batch just happens to be 1 image
        # the batch norm will fail
        if len(batch[0]) < 2:
          return None

        batch_result = self.train_batch(batch)
        count, _, _ = batch_result
        self.train_stats.append(batch_result)
        self.checkpoint += count

        return self.compile_and_reset_train_stats()\
            if self.checkpoint >= self.images_per_checkpoint\
            else None

    def compile_and_reset_train_stats(self):
        """
        Compile a training set result and reset totals to 0
        """

        stats = compile_stats(self.train_stats)
        ch = self.checkpoint

        self.train_stats = []
        self.checkpoint = 0

        return ch, stats

    def train_batch(self, batch):
        """
        Train on a batch, updating gradients and return results
        """

        loss, result = self.execute_batch(batch)
        loss.backward()
        self.optimizer.step()
        self.optimizer.zero_grad()
        self.scheduler.step(loss.item())

        return result

    def execute_batch(self, batch):
        """
        Execute a single batch and return results
        """

        inputs, labels = batch
        inputs, labels = inputs.to(self.device), labels[:,0].to(self.device)
        outputs = self.model(inputs)

        loss = self.loss_fn(outputs, labels)
        results = outputs.argmax(1) == labels
        return loss, (
            len(results),
            loss.item(),
            results.type(torch.float).mean().item())

    def validate(self):
        """
        Execute the entire validation data set and return loss and acc stats
        """

        self.model.train(False)
        try:
            stats = map(lambda x: self.execute_batch(x)[1], self.data_val)
            return compile_stats(stats)

        finally:
            self.model.train(True)

class LoggedTrainer():
    def __init__(self, name, trainer):
        """
        images_per_checkpoint:  the number of images to process before emitting
                                and event to the tensorboard writer
        """
        self.writer = None
        self.name = name
        self.trainer = trainer
        self.total_images = 0
        self.best_val_acc = 0

    def __enter__(self):
        self.writer = SummaryWriter(f'tensorboard/{round(datetime.now().timestamp())}')
        return self

    def __exit__(self, exception_type, exception_value, exception_traceback):
        self.writer.close()

    def train(self):
        """
        Train the entire model and emit results to tensorboard
        """

        for epoch, event in self.trainer.train():
            event_batch_size, (train_loss, train_acc) = event
            val_loss, val_acc = self.trainer.validate()
            self.write(epoch, event_batch_size, train_loss, train_acc, val_loss, val_acc)

            if val_acc > 0.7 and val_acc > self.best_val_acc + 0.001:
                print("Persisting model")
                torch.save(self.trainer.model.state_dict(), "./best_results/best.model")
                torch.save(self.trainer.model.state_dict(), f"./best_results/{val_acc}.model")
                self.best_val_acc = val_acc

    def write(self, epoch, event_batch_size, train_loss, train_acc, val_loss, val_acc):
        """
        Write test/validation stats to tensorboard
        """

        self.total_images += event_batch_size

        # TODO https://stackoverflow.com/questions/48951136/plot-multiple-graphs-in-one-plot-using-tensorboard
        print(f"Training Error, epoch {epoch}: \n Accuracy: {(train_acc*100):>0.1f}%, Avg loss: {train_loss:>8f}")
        print(f"Validation Error, epoch {epoch}: \n Accuracy: {(val_acc*100):>0.1f}%, Avg loss: {val_loss:>8f}\n")

        # Log the running loss averaged per batch
        self.writer.add_scalars('Loss',
                        { f'Training Loss {self.name}' : train_loss, f'Validation Loss {self.name}' : val_loss },
                        self.total_images)
        self.writer.add_scalars('Accuracy',
                        {f'Training Acc {self.name}' : train_acc, f'Validation Acc {self.name}' : val_acc },
                        self.total_images)

        self.writer.flush()

